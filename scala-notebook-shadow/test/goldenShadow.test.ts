import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import test from "node:test";
import { CONFIG_DEFAULTS } from "../src/configDefaults";
import { transform } from "../src/transform";
import { loadNotebookCells, projectRoot, repoRoot } from "./notebookFixture";

/**
 * A golden test over the real fixture notebook.
 *
 * The other transform tests each pin one rule with a hand-written cell. This one pins
 * what those rules add up to on a whole notebook a person actually opens in VS Code:
 * header, prelude, cell markers, `$ivy` rewriting and deduplication, result bindings and
 * scope nesting all in one file, in their real order. It is the test that notices when
 * two individually-correct rules stop composing.
 *
 * `fixture/notebook-shadow/` is generated by the extension and gitignored, so the
 * expected output is committed here instead. Regenerate after a deliberate change:
 *
 *     UPDATE_GOLDEN=1 npm test
 */
const notebookPath = path.join(repoRoot, "fixture", "sample.ipynb");
const goldenPath = path.join(projectRoot, "test", "golden", "sample.scala");

/** The shadow the extension would write for `fixture/sample.ipynb` with no settings set. */
function generate(): string {
  const cells = loadNotebookCells(notebookPath);
  return transform(cells, { ...CONFIG_DEFAULTS, wrapperObjectName: "sample" }).text;
}

test("the fixture notebook still produces the committed shadow file", () => {
  const actual = generate();

  if (process.env.UPDATE_GOLDEN) {
    fs.writeFileSync(goldenPath, actual);
  }

  // Read tolerantly: a checkout with core.autocrlf on rewrites the golden's line endings,
  // which says nothing about the transform.
  const expected = fs.readFileSync(goldenPath, "utf8").replace(/\r\n/g, "\n");
  assert.equal(actual, expected);
});

test("cell spans cover the notebook's Scala cells, skipping its markdown", () => {
  const cells = loadNotebookCells(notebookPath);
  const { mapping } = transform(cells, { ...CONFIG_DEFAULTS, wrapperObjectName: "sample" });

  const codeCellIndices = cells.filter((cell) => cell.isCode).map((cell) => cell.index);
  assert.deepEqual(
    mapping.spans.map((span) => span.cellIndex),
    codeCellIndices
  );

  // Spans are ordered and disjoint, which the binary search in lineToSpan relies on.
  for (let i = 1; i < mapping.spans.length; i++) {
    const previous = mapping.spans[i - 1];
    assert.ok(
      mapping.spans[i].startLine >= previous.startLine + previous.lineCount,
      `span ${i} starts inside span ${i - 1}`
    );
  }
});
